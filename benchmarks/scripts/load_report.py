#!/usr/bin/env python3
"""Tables for docs/15 from benchmarks/results/load/*.jsonl (every number in docs/15 comes from here).

Usage: python benchmarks/scripts/load_report.py   ->  benchmarks/results/load/REPORT.md + analysis.json
"""

import sys
import json
from typing import Any
import statistics as st
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from llmserve.costmodel import CostModel, _lstsq  # noqa: E402

RES = ROOT / "benchmarks/results/load"


def rows(name: str) -> list[dict[str, Any]]:
    p = RES / name
    return (
        [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines() if line.strip()] if p.exists() else []
    )


def cache_share(rs: list[dict[str, Any]]) -> float | None:
    """Share of prompt tokens served from the KV cache, over turns after the first of each session."""
    later = [r for r in rs if r["status"] == 200 and r["turn"] > 0 and r["prompt_new"] is not None]
    total = sum(r["prompt_new"] + r["prompt_cached"] for r in later)
    return round(sum(r["prompt_cached"] for r in later) / total, 3) if total else None


def fmt(x: Any) -> str:
    return "–" if x is None else (f"{x:g}" if isinstance(x, float) else str(x))


def main() -> None:
    out: dict[str, Any] = {}
    md: list[str] = ["# Load test report (generated by benchmarks/scripts/load_report.py)\n"]

    # ---- simulator tables: one row per (tag, sessions), from every runs-*/ directory
    sim_rows = {
        d: (rows(f"{d}/sim_summary.jsonl"), rows(f"{d}/sim.jsonl"))
        for d in ("runs-a", "runs-b", "runs-c", "runs-cline")
    }

    def table(title: str, dirs: tuple[str, ...], prefix: str, label: Any) -> list[dict[str, Any]]:
        md.append(f"## {title}\n")
        md.append(
            "| config | sessions | turns ok | 429s | gave up | TTFT p50 | TTFT p95 | turn p50 | turn p95 "
            "| gen tok/s | cached share |"
        )
        md.append("|---|---|---|---|---|---|---|---|---|---|---|")
        got = []
        for d in dirs:
            summ, sim = sim_rows[d]
            for sm in summ:
                if not sm["tag"].startswith(prefix):
                    continue
                rs = [
                    r
                    for r in sim
                    if r["tag"] == sm["tag"] and r["sessions"] == sm["sessions"] and r["stamp"] == sm["stamp"]
                ]
                row = {
                    "config": label(sm),
                    "tag": sm["tag"],
                    "dir": d,
                    "sessions": sm["sessions"],
                    "ok": sm["ok"],
                    "requests": sm["requests"],
                    "rejected_429": sm["rejected_429"],
                    "gave_up": sm["gave_up"],
                    "ttft": sm["ttft_s"],
                    "turn": sm["turn_s"],
                    "gen_tok_per_s": sm["gen_tok_per_s"],
                    "cached_share": cache_share(rs),
                }
                got.append(row)
                md.append(
                    f"| {row['config']} | {sm['sessions']} | {sm['ok']}/{sm['requests']} | {sm['rejected_429']} "
                    f"| {sm['gave_up']} | {fmt(sm['ttft_s']['p50'])} | {fmt(sm['ttft_s']['p95'])} "
                    f"| {fmt(sm['turn_s']['p50'])} | {fmt(sm['turn_s']['p95'])} | {fmt(sm['gen_tok_per_s'])} "
                    f"| {fmt(row['cached_share'])} |"
                )
        md.append("")
        return got

    def adm(sm: dict[str, Any]) -> str:
        return "no admission" if sm.get("max_queue") is None else f"queue ≤ {sm['max_queue']}"

    def sched(sm: dict[str, Any]) -> str:
        parts = [f"{sm.get('slots', 1)} slot{'s' if sm.get('slots', 1) > 1 else ''}"]
        if sm.get("slots", 1) > 1:
            parts.append(f"beta {sm['beta']}")
        parts.append(sm.get("policy", "fifo"))
        if sm.get("hold_s"):
            guard = sm.get("hold_max_wait_s")  # runs before the fairness guard existed have no such field
            parts.append(
                f"hold {sm['hold_s']:g} s, "
                + ("no fairness guard" if guard is None or guard >= 1e8 else f"guard {guard:g} s")
            )
        parts.append(f"ctx cap {sm.get('max_context', 60000) // 1000}k")
        return ", ".join(parts)

    out["e_load"] = table(
        "E-LOAD: admission control (simulator, live-calibrated service times, agent workload)",
        ("runs-a",),
        "e-load",
        adm,
    )
    out["e_load_cline_model"] = table(
        "E-LOAD sensitivity: the same sweep with the Oct 6 Cline-log service times (cold prefill ~26% slower)",
        ("runs-cline",),
        "e-load",
        adm,
    )
    out["e_sched"] = table(
        "E-SCHED: queue order and anticipatory hold (one slot, queue ≤ 8, no rejections)",
        ("runs-a", "runs-b", "runs-c"),
        "e-sched",
        sched,
    )
    out["e_np2"] = table(
        "E-NP2: two slots vs one, same 30k client context cap (beta is an assumption)", ("runs-b",), "e-np2", sched
    )

    # ---- robustness: the three main contenders over seeds 0-2 (seed 0 = the runs above)
    contenders = {
        "1 slot, FIFO": [("runs-a", "e-sched-fifo")] + [(f"runs-d-{k}", "e-seed-fifo") for k in (1, 2)],
        "1 slot, hold 15 s + guard": [("runs-c", "e-sched-hold15-guard")]
        + [(f"runs-d-{k}", "e-seed-hold15-guard") for k in (1, 2)],
        "2 slots (beta 0.6)": [("runs-b", "e-np2-beta0.6")] + [(f"runs-d-{k}", "e-seed-np2") for k in (1, 2)],
    }
    for k in (1, 2):
        sim_rows[f"runs-d-{k}"] = (rows(f"runs-d-{k}/sim_summary.jsonl"), rows(f"runs-d-{k}/sim.jsonl"))
    md.append("## Robustness: three seeds (different think times, prompt and answer lengths)\n")
    md.append("Each cell: mean over the seeds that ran, with the range in brackets. n = turns per seed.\n")
    md.append("| config | sessions | seeds | TTFT p50 | TTFT p95 | turn p50 | turn p95 | cached share | turns failed |")
    md.append("|---|---|---|---|---|---|---|---|---|")
    robust = []
    for label, sources in contenders.items():
        for n in (2, 4):
            vals: dict[str, list[float]] = defaultdict(list)
            failed = 0
            seeds = 0
            for d, tag in sources:
                summ, sim = sim_rows[d]
                for sm in summ:
                    if sm["tag"] == tag and sm["sessions"] == n:
                        seeds += 1
                        rs = [r for r in sim if r["tag"] == tag and r["sessions"] == n and r["stamp"] == sm["stamp"]]
                        vals["ttft50"].append(sm["ttft_s"]["p50"])
                        vals["ttft95"].append(sm["ttft_s"]["p95"])
                        vals["turn50"].append(sm["turn_s"]["p50"])
                        vals["turn95"].append(sm["turn_s"]["p95"])
                        vals["cached"].append(cache_share(rs) or 0.0)
                        failed += sm["requests"] - sm["ok"]
            if not seeds:
                continue

            def cell(xs: list[float]) -> str:
                return f"{st.mean(xs):.1f} [{min(xs):.1f}–{max(xs):.1f}]" if len(xs) > 1 else f"{xs[0]:.1f}"

            robust.append(
                {
                    "config": label,
                    "sessions": n,
                    "seeds": seeds,
                    "failed": failed,
                    **{k: {"mean": round(st.mean(v), 2), "min": min(v), "max": max(v)} for k, v in vals.items()},
                }
            )
            md.append(
                f"| {label} | {n} | {seeds} | {cell(vals['ttft50'])} | {cell(vals['ttft95'])} "
                f"| {cell(vals['turn50'])} | {cell(vals['turn95'])} | {st.mean(vals['cached']):.2f} | {failed} |"
            )
    md.append("")
    out["robustness"] = robust

    # ---- live black-box runs
    live = rows("load.jsonl")
    lsum = rows("load_summary.jsonl")
    md.append("\n## Live black-box runs (real endpoint, small agent workload: 4 turns, ≤300 output tokens)\n")
    md.append(
        "| sessions | turns ok | 429s | TTFT p50 | TTFT p95 | turn p50 | turn p95 | cached share | Retry-After seen |"
    )
    md.append("|---|---|---|---|---|---|---|---|---|")
    out["live"] = []
    for s in lsum:
        rs = [r for r in live if r["sessions"] == s["sessions"] and r["stamp"] == s["stamp"]]
        ra = sorted({r["retry_after_s"] for r in rs if r["retry_after_s"] is not None})
        row = {"sessions": s["sessions"], "summary": s, "cached_share": cache_share(rs), "retry_after": ra}
        out["live"].append(row)
        md.append(
            f"| {s['sessions']} | {s['ok']}/{s['requests']} | {s['rejected_429']} | {fmt(s['ttft_s']['p50'])} "
            f"| {fmt(s['ttft_s']['p95'])} | {fmt(s['turn_s']['p50'])} | {fmt(s['turn_s']['p95'])} "
            f"| {fmt(row['cached_share'])} | {', '.join(fmt(x) for x in ra) or '–'} |"
        )

    # ---- simulator validation, per request: cost model vs llama.cpp's own timings on the live runs
    ok = [r for r in live if r["status"] == 200 and r["prefill_s"]]
    # the very first request warmed the server up; the runs went 1, 2, 4 sessions within one stamp
    first = min(ok, key=lambda r: (r["stamp"], r["sessions"], r["start_s"]))
    cold = [r for r in ok if r["prompt_cached"] == 0 and r is not first]
    train = [r for r in cold if r["sessions"] in (1, 2)]
    test = [r for r in cold if r["sessions"] == 4]
    a, b = _lstsq([[1.0, r["prompt_new"]] for r in train], [r["prefill_s"] for r in train])
    cline = CostModel()
    live_fit = CostModel(overhead_s=a, prefill_tps=1 / b)

    def err(model: CostModel, rs: list[dict[str, Any]]) -> dict[str, float]:
        e = [model.prefill_s(r["prompt_new"], r["prompt_cached"]) / r["prefill_s"] - 1 for r in rs]
        return {"n": len(e), "median_rel_err": round(st.median(e), 3), "max_abs_rel_err": round(max(map(abs, e)), 3)}

    dec = [(1 / cline.token_s(r["prompt_new"] + r["prompt_cached"])) / r["gen_tps"] - 1 for r in ok if r["gen_tps"]]
    val = {
        "first_request": {
            "new": first["prompt_new"],
            "prefill_s": first["prefill_s"],
            "model_s": round(cline.prefill_s(first["prompt_new"], 0), 2),
        },
        "cold_prefill_cline_model_on_test": err(cline, test),
        "cold_prefill_live_fit": {
            "overhead_s": round(a, 3),
            "prefill_tps": round(1 / b, 1),
            "train_n": len(train),
            "test": err(live_fit, test),
        },
        "warm_prefill_cline_model": err(cline, [r for r in ok if r["prompt_cached"] > 0]),
        "decode_cline_model": {
            "n": len(dec),
            "median_rel_err": round(st.median(dec), 3),
            "max_abs_rel_err": round(max(map(abs, dec)), 3),
        },
    }
    out["validation"] = val
    md.append("\n## Simulator validation: cost model vs llama.cpp `timings` of the live requests\n")
    md.append("| component | model | n | median error | worst error |")
    md.append("|---|---|---|---|---|")
    v = val
    md.append(
        f"| decode tok/s | Cline-log fit | {v['decode_cline_model']['n']} "
        f"| {v['decode_cline_model']['median_rel_err']:+.1%} | {v['decode_cline_model']['max_abs_rel_err']:.1%} |"
    )
    c = v["cold_prefill_cline_model_on_test"]
    md.append(
        f"| cold prefill (4-session run) | Cline-log fit (Oct 6) | {c['n']} | {c['median_rel_err']:+.1%} "
        f"| {c['max_abs_rel_err']:.1%} |"
    )
    lf = v["cold_prefill_live_fit"]
    md.append(
        f"| cold prefill (4-session run) | live fit on the 1–2 session runs ({lf['overhead_s']} s + new/"
        f"{lf['prefill_tps']} tok/s) | {lf['test']['n']} | {lf['test']['median_rel_err']:+.1%} "
        f"| {lf['test']['max_abs_rel_err']:.1%} |"
    )
    w = v["warm_prefill_cline_model"]
    md.append(
        f"| prefill with a cache hit | Cline-log fit | {w['n']} | {w['median_rel_err']:+.1%} "
        f"| {w['max_abs_rel_err']:.1%} |"
    )
    f = v["first_request"]
    md.append(
        f"\nFirst request of the session (warm-up, excluded above): {f['new']} new tokens, prefill "
        f"{f['prefill_s']} s vs {f['model_s']} s predicted.\n"
    )

    # ---- per-turn cache hits in the live 2-session run: the thrash, request by request
    two = sorted([r for r in live if r["sessions"] == 2 and r["status"] == 200], key=lambda r: r["start_s"])
    one = sorted([r for r in live if r["sessions"] == 1 and r["status"] == 200], key=lambda r: r["start_s"])
    md.append("## Cache thrash, live: TTFT and cached tokens per turn\n")
    md.append("| run | turn | session | new tokens | cached tokens | TTFT s |")
    md.append("|---|---|---|---|---|---|")
    for label, rs in (("1 session", one), ("2 sessions", two)):
        for r in rs:
            md.append(
                f"| {label} | {r['turn']} | {r['session']} | {r['prompt_new']} | {r['prompt_cached']} "
                f"| {r['ttft_s']:.1f} |"
            )

    (RES / "analysis.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (RES / "REPORT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {RES / 'REPORT.md'} and {RES / 'analysis.json'}")


if __name__ == "__main__":
    main()
